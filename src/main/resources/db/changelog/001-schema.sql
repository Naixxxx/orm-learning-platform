CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('STUDENT', 'TEACHER', 'ADMIN')),
    CONSTRAINT email_normalized CHECK (email = lower(email))
);

CREATE TABLE profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    account_id BIGINT NOT NULL UNIQUE REFERENCES accounts(id) ON DELETE CASCADE,
    biography VARCHAR(2000),
    avatar_url VARCHAR(1000)
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    name VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    title VARCHAR(200) NOT NULL,
    description VARCHAR(10000) NOT NULL,
    teacher_id BIGINT NOT NULL REFERENCES accounts(id),
    category_id BIGINT NOT NULL REFERENCES categories(id),
    start_date DATE
);

CREATE TABLE course_tags (
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES tags(id),
    PRIMARY KEY (course_id, tag_id)
);

CREATE TABLE course_modules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    description VARCHAR(4000),
    position INTEGER NOT NULL CHECK (position > 0),
    UNIQUE (course_id, position)
);

CREATE TABLE lessons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    module_id BIGINT NOT NULL REFERENCES course_modules(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    content VARCHAR(30000) NOT NULL,
    position INTEGER NOT NULL CHECK (position > 0),
    UNIQUE (module_id, position)
);

CREATE TABLE enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    student_id BIGINT NOT NULL REFERENCES accounts(id),
    course_id BIGINT NOT NULL REFERENCES courses(id),
    enrolled_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE', 'COMPLETED')),
    UNIQUE (student_id, course_id)
);

CREATE TABLE assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    lesson_id BIGINT NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    description VARCHAR(10000) NOT NULL,
    due_at TIMESTAMPTZ,
    max_score INTEGER NOT NULL CHECK (max_score BETWEEN 1 AND 10000)
);

CREATE TABLE submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    student_id BIGINT NOT NULL REFERENCES accounts(id),
    assignment_id BIGINT NOT NULL REFERENCES assignments(id),
    content VARCHAR(30000) NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL,
    score INTEGER CHECK (score >= 0),
    feedback VARCHAR(4000),
    UNIQUE (student_id, assignment_id)
);

CREATE TABLE quizzes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    module_id BIGINT NOT NULL UNIQUE REFERENCES course_modules(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    pass_percent INTEGER NOT NULL CHECK (pass_percent BETWEEN 0 AND 100)
);

CREATE TABLE questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    quiz_id BIGINT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
    text VARCHAR(4000) NOT NULL,
    type VARCHAR(30) NOT NULL CHECK (type IN ('SINGLE_CHOICE', 'MULTIPLE_CHOICE')),
    position INTEGER NOT NULL CHECK (position > 0),
    points INTEGER NOT NULL CHECK (points BETWEEN 1 AND 1000),
    UNIQUE (quiz_id, position)
);

CREATE TABLE answer_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    text VARCHAR(2000) NOT NULL,
    correct BOOLEAN NOT NULL,
    position INTEGER NOT NULL CHECK (position > 0),
    UNIQUE (question_id, position)
);

CREATE TABLE quiz_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    student_id BIGINT NOT NULL REFERENCES accounts(id),
    quiz_id BIGINT NOT NULL REFERENCES quizzes(id),
    score INTEGER NOT NULL CHECK (score >= 0),
    max_score INTEGER NOT NULL CHECK (max_score > 0 AND score <= max_score),
    passed BOOLEAN NOT NULL,
    taken_at TIMESTAMPTZ NOT NULL,
    UNIQUE (student_id, quiz_id)
);

CREATE TABLE course_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    student_id BIGINT NOT NULL REFERENCES accounts(id),
    course_id BIGINT NOT NULL REFERENCES courses(id),
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(4000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (student_id, course_id)
);

CREATE TABLE lesson_materials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    lesson_id BIGINT NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    url VARCHAR(1000) NOT NULL
);

CREATE TABLE scheduled_lessons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    lesson_id BIGINT NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    meeting_url VARCHAR(1000) NOT NULL,
    CHECK (ends_at > starts_at)
);

CREATE TABLE lesson_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    student_id BIGINT NOT NULL REFERENCES accounts(id),
    lesson_id BIGINT NOT NULL REFERENCES lessons(id),
    completed_at TIMESTAMPTZ NOT NULL,
    UNIQUE (student_id, lesson_id)
);

CREATE INDEX courses_teacher_idx ON courses(teacher_id);
CREATE INDEX courses_category_idx ON courses(category_id);
CREATE INDEX course_tags_tag_idx ON course_tags(tag_id);
CREATE INDEX enrollments_course_idx ON enrollments(course_id);
CREATE INDEX assignments_lesson_idx ON assignments(lesson_id);
CREATE INDEX submissions_assignment_idx ON submissions(assignment_id);
CREATE INDEX quiz_submissions_quiz_idx ON quiz_submissions(quiz_id);
CREATE INDEX course_reviews_course_idx ON course_reviews(course_id);
CREATE INDEX lesson_materials_lesson_idx ON lesson_materials(lesson_id);
CREATE INDEX scheduled_lessons_lesson_idx ON scheduled_lessons(lesson_id, starts_at);
CREATE INDEX lesson_progress_lesson_idx ON lesson_progress(lesson_id);
